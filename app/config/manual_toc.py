def lookup_manual_metadata(chapter_no: int, section_no: int, item_no: int, title: str) -> dict[str, str]:
    chapter_entry = MANUAL_TOC.get(chapter_no, {})
    sections = chapter_entry.get("sections", {})
    section_name = sections.get(section_no)

    metadata = {
        "title": title,
        "chapter": chapter_entry.get("chapter", f"제{chapter_no}편"),
        "section": section_name or f"제{section_no}장",
        "item_no": str(item_no),
    }

    if section_name:
        metadata["section_no"] = str(section_no)

    return metadata
